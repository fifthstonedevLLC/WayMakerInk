/* ==========================================================================
   Generate 02-import-existing-requests.sql from the Sheet export.

     node build-import-sql.js

   Why a generator rather than a hand-written .sql: the export is 42 rows of
   client free text containing apostrophes and newlines, and hand-building SQL
   string literals around that is how a migration silently truncates someone's
   description at the first quote. The generated file embeds the export as ONE
   dollar-quoted JSON literal and lets Postgres do the parsing, so no value is
   ever escaped by us.

   Re-run it if the export is re-taken. The transformations live in the SQL it
   emits, not here — this file only wraps the payload, so the mapping stays
   readable in the artefact that actually runs.
   ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'migrations', 'existing_client_data_migration.json');
const OUT = path.join(__dirname, '02-import-existing-requests.sql');
const TAG = '$wm_import$';

const rows = JSON.parse(fs.readFileSync(SRC, 'utf8'));
if (!Array.isArray(rows) || !rows.length) {
  throw new Error(`${SRC} is not a non-empty array.`);
}

/* Compact, so the payload is one line and diffs on this file stay legible. */
const payload = JSON.stringify(rows);

/* The one way dollar quoting can break. Nothing in a booking request should
   contain this, but a migration that corrupts on an unchecked assumption is
   worse than one that refuses to generate. */
if (payload.includes(TAG)) {
  throw new Error(`Export contains the dollar-quote tag ${TAG}; pick another tag.`);
}

/* Reported in the header so the generated file states what it was built from
   and anyone reading it can tell at a glance whether it matches the export. */
const rids = new Set(rows.map((r) => r.rid));
const dupes = rows.length - rids.size;
const byStatus = {};
rows.forEach((r) => { byStatus[r.status] = (byStatus[r.status] || 0) + 1; });

/* The same de-duplication the SQL does, run here so the generated file can
   state its own expected counts. If these two ever disagree the verify block
   fails loudly, which is the point — a check whose expectations are copied by
   hand stops being a check the first time the export changes. */
const bucket = {};
rows.forEach((r) => { (bucket[r.rid] = bucket[r.rid] || []).push(r); });
const kept = Object.values(bucket).map((v) => v.slice().sort((a, b) => {
  const ad = String(a.decidedAt || '').trim() ? 0 : 1;
  const bd = String(b.decidedAt || '').trim() ? 0 : 1;
  return ad - bd || a.row_number - b.row_number;
})[0]);

const expected = {};
kept.forEach((r) => {
  const k = r.artistKey + '|' + String(r.status).trim().replace(/ /g, '_');
  expected[k] = (expected[k] || 0) + 1;
});

/* One row per artist/status pair, plus the totals and the constraint sweep.
   Emitted as a single UNION so the Supabase SQL Editor — which shows only the
   last statement's result — displays the whole thing rather than the tail. */
const checkRows = [
  `  select 1 as ord, 'requests imported'::text as check_name, '${kept.length}'::text as expected, count(*)::text as actual from public.requests`,
  `  select 2, 'migrated events', '${kept.length}', count(*)::text from public.request_events where event = 'migrated'`,
  ...Object.entries(expected).sort().map(([k, v], i) => {
    const [artist, status] = k.split('|');
    return `  select ${10 + i}, '${artist} / ${status}', '${v}', count(*)::text from public.requests where artist_key = '${artist}' and status = '${status}'`;
  }),
  `  select 90, 'rows with no images loaded', '${kept.filter((r) => Number(r.referenceCount) > 0).length}', count(*)::text from public.requests where reference_count > 0`,
  `  select 98, 'decided rows missing a decision', '0', count(*)::text from public.requests where status in ('LINK_SENT','DECLINED') and (decided_at is null or (status = 'LINK_SENT' and tier_sent is null))`,
  `  select 99, 'rows with an unknown artist', '0', count(*)::text from public.requests r left join public.artists a on a.key = r.artist_key where a.key is null`
].join('\n  union all\n');

const sql = `-- ==========================================================================
-- WayMaker Ink — import the Google Sheet request history
--
-- GENERATED by import/build-import-sql.js from
-- migrations/existing_client_data_migration.json. Do not hand-edit; re-run the
-- generator instead.
--
--   source rows        ${rows.length}
--   distinct rids      ${rids.size}
--   dropped as dupes   ${dupes}
--   by sheet status    ${Object.entries(byStatus).map(([k, v]) => `${k}=${v}`).join('  ')}
--
-- Run as \`postgres\` (SQL Editor or psql). There is no insert policy on
-- public.requests — intake is a function, so writes come from service_role and
-- RLS has nothing to grant an ordinary session here.
--
-- Idempotent: \`on conflict (rid) do nothing\`. Running it twice imports
-- nothing the second time, so a partial run is safe to repeat.
--
-- ---------------------------------------------------------------- mapping ---
-- The sheet stored what a person reads; this schema stores what code branches
-- on. Every transformation below is one the Edge Function does at the door for
-- live traffic (see the schema header), applied here to history instead.
--
--   status  'LINK SENT'  ->  'LINK_SENT'         no spaces, ever
--   service ''           ->  'tattoo'            every exported row predates
--                                                the service column
--   firstTattoo 'Yes'    ->  first_time  true    real boolean
--   minorAge ''          ->  minor_age   NULL    real integer, or nothing
--   tierSent ''          ->  tier_sent   NULL    NOT '', which would satisfy
--                                                requests_decided_has_decision
--                                                without naming a tier
--   heardFrom ''         ->  'Not given'         the column's own default
--
-- Dropped, because the schema holds them elsewhere or not at all:
--   artistName, artistEmail   -> the artist_key foreign key carries both
--   driveFolder, row_number   -> preserved on the 'migrated' event, below
--
-- ------------------------------------------------------------- duplicates ---
-- The export has ${rows.length} rows and ${rids.size} distinct rids. The extras are the
-- retry duplicates the sheet had no way to prevent and this schema's unique
-- constraint on rid now does: the same submission landed twice, the artist
-- answered one copy, and the other is still sitting at NEW.
--
-- Keep the answered copy. Ranking is decidedAt-first, then the earlier sheet
-- row, so the surviving row is the one carrying the artist's actual decision
-- and the NEW twin is dropped. Importing both is impossible; importing the
-- wrong one would erase a decision that was really made.
--
-- ------------------------------------------------------------ what is lost ---
-- Reference IMAGES do not come across. They are in Drive, not in Storage, and
-- there is nothing to point request_images at. reference_count is imported
-- honestly anyway, so the portal shows "0 of 2 loaded" rather than pretending
-- the client sent nothing — and the Drive folder NAME is on the migrated event
-- so the originals stay findable.
--
-- booking_url is also empty: the sheet never recorded which Acuity URL was
-- mailed, only the tier. tier_sent is imported and is the closest record there
-- is.
-- ==========================================================================

begin;

with src as (
  select
    r,
    (r->>'row_number')::int as sheet_row
  from jsonb_array_elements(${TAG}${payload}${TAG}::jsonb) as t(r)
),

/* One row per rid. A decided row outranks an undecided one; ties break on the
   earlier sheet row so the result is deterministic rather than whatever order
   the export happened to be in. */
ranked as (
  select
    src.*,
    row_number() over (
      partition by src.r->>'rid'
      order by
        case when nullif(trim(src.r->>'decidedAt'), '') is not null then 0 else 1 end,
        src.sheet_row
    ) as pick
  from src
),

keep as (
  select * from ranked where pick = 1
),

inserted as (
  insert into public.requests (
    rid, status, service, artist_key,
    first_name, last_name, email, phone,
    client_is_minor, first_time, heard_from, referred_by,
    idea, placement, size, style,
    piercing_type, piercing_count, piercing_side, jewelry, piercing_notes,
    minor_first_name, minor_last_name, minor_age,
    guardian_relationship, guardian_consent,
    submitted_at, page_url, reference_count,
    tier_sent, estimate, artist_note, decided_at,
    created_at
  )
  select
    keep.r->>'rid',

    /* 'LINK SENT' is the only value with a space in it, but replace() covers
       any future one rather than matching that single string. */
    replace(trim(keep.r->>'status'), ' ', '_'),

    /* Every exported row predates the service column, so the export has '' in
       all ${rows.length}. coalesce rather than a literal, so a later export that DOES
       carry the column imports correctly without editing this file. */
    coalesce(nullif(lower(trim(keep.r->>'service')), ''), 'tattoo'),

    keep.r->>'artistKey',

    keep.r->>'firstName',
    keep.r->>'lastName',
    keep.r->>'email',
    coalesce(keep.r->>'phone', ''),

    coalesce(trim(keep.r->>'clientIsMinor') = 'Yes', false),
    coalesce(trim(keep.r->>'firstTattoo') = 'Yes', false),
    coalesce(nullif(trim(keep.r->>'heardFrom'), ''), 'Not given'),
    coalesce(keep.r->>'referredBy', ''),

    coalesce(keep.r->>'idea', ''),
    coalesce(keep.r->>'placement', ''),
    coalesce(keep.r->>'size', ''),
    coalesce(keep.r->>'style', ''),

    coalesce(keep.r->>'piercingType', ''),
    coalesce(keep.r->>'piercingCount', ''),
    coalesce(keep.r->>'piercingSide', ''),
    coalesce(keep.r->>'jewelry', ''),
    coalesce(keep.r->>'piercingNotes', ''),

    coalesce(keep.r->>'minorFirstName', ''),
    coalesce(keep.r->>'minorLastName', ''),
    nullif(trim(keep.r->>'minorAge'), '')::smallint,
    coalesce(keep.r->>'guardianRelationship', ''),
    coalesce(trim(keep.r->>'guardianConsent') = 'Yes', false),

    (keep.r->>'submittedAt')::timestamptz,
    coalesce(keep.r->>'pageUrl', ''),
    coalesce(nullif(trim(keep.r->>'referenceCount'), '')::smallint, 0),

    /* NULL, not ''. requests_decided_has_decision tests \`tier_sent is not
       null\`, so an empty string would let a LINK_SENT row through naming no
       tier at all. */
    nullif(trim(keep.r->>'tierSent'), ''),
    coalesce(keep.r->>'estimate', ''),
    coalesce(keep.r->>'artistNote', ''),
    nullif(trim(keep.r->>'decidedAt'), '')::timestamptz,

    /* Not now(). A migrated row's created_at is when the client submitted it,
       or every imported request sorts as though it arrived the day of the
       migration and the queue is meaningless. */
    (keep.r->>'submittedAt')::timestamptz

  from keep
  on conflict (rid) do nothing
  returning id, rid
)

/* Provenance, and the home for the three fields the schema has no column for.
   decided_by stays null on the request itself: these decisions were made in
   the old system by someone with no auth.users row, and inventing an actor
   would be a lie in an audit table. */
insert into public.request_events (request_id, event, detail, created_at)
select
  inserted.id,
  'migrated',
  jsonb_build_object(
    'source', 'google-sheet',
    'sheet_row', keep.sheet_row,
    'original_status', keep.r->>'status',
    'drive_folder', keep.r->>'driveFolder',
    'artist_name', keep.r->>'artistName',
    'artist_email', keep.r->>'artistEmail',
    'reference_count', coalesce(nullif(trim(keep.r->>'referenceCount'), '')::int, 0),
    'note', 'Imported from the Request Queue sheet. Reference images remain in Drive.'
  ),
  now()
from inserted
join keep on keep.r->>'rid' = inserted.rid;

commit;


-- ============================================================== verify ====
-- ONE result set on purpose: the Supabase SQL Editor shows only the last
-- statement's output, so three separate selects would display the third and
-- silently discard the two that mattered.
--
-- Read the \`ok\` column. Every row must say PASS. The expected values are
-- generated from the export itself, not typed in, so they cannot drift from
-- the data being imported.

select
  check_name,
  expected,
  actual,
  case when expected = actual then 'PASS' else '*** FAIL ***' end as ok
from (
${checkRows}
) as checks
order by ord;
`;

fs.writeFileSync(OUT, sql, 'utf8');
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
console.log(`  ${rows.length} source rows -> ${rids.size} imported (${dupes} duplicate rid${dupes === 1 ? '' : 's'} dropped)`);
